CREATE OR REPLACE VIEW game_curriculum_to_evaluate AS
SELECT 'concept' AS kind, c.name AS code, c.title,
       count(cs.*) AS sources, count(cs.*) FILTER (WHERE NOT cs.verified OR NOT s.verified) AS unverified
  FROM game_concepts c
  LEFT JOIN game_concept_sources cs ON cs.concept_id = c.id
  LEFT JOIN game_sources s ON s.id = cs.source_id
 GROUP BY c.id
HAVING count(cs.*) < 2 OR count(cs.*) FILTER (WHERE NOT cs.verified OR NOT s.verified) > 0
UNION ALL
SELECT 'technique', t.code, t.title,
       count(ts.*), count(ts.*) FILTER (WHERE NOT ts.verified OR NOT s.verified)
  FROM game_techniques t
  LEFT JOIN game_technique_sources ts ON ts.technique_id = t.id
  LEFT JOIN game_sources s ON s.id = ts.source_id
 WHERE t.node = 'technique'
 GROUP BY t.id
HAVING count(ts.*) < 2 OR count(ts.*) FILTER (WHERE NOT ts.verified OR NOT s.verified) > 0;
COMMENT ON VIEW game_curriculum_to_evaluate IS 'James: flag the ones that have only 1 source (or an unverified one) and evaluate.';
