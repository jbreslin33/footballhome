-- Owner 2026-11-11: "instead of city should we use metro area?" → yes, load
-- the Census list and judge by metros, Hartford as the bar → "yes do it".
--
-- * pyramid_metro_areas / pyramid_metro_counties: the OMB July 2023 CBSA
--   delineation (Census list1_2023.xlsx — metropolitan and micropolitan
--   areas, their counties, central/outlying, combined area).  Connecticut's
--   2023 planning regions are mapped back onto the 8 counties our map uses
--   (Fairfield → Bridgeport-Stamford; Hartford, Middlesex, Tolland →
--   Hartford; New Haven → New Haven; New London, Windham → Norwich-New
--   London; Litchfield → Torrington).  Population = sum of our county rows.
-- * Tier: a proposal's people = its base city's metro area; the bar = the
--   smallest metro area that anchors a live conference (Hartford, ~1.2 M —
--   view pyramid_proposal_bar, also read by GET /api/pyramid/proposal, which
--   until now still measured the bar by nearest APSL ground).  Ready ≥ bar,
--   borderline ≥ 75 % of it, else watch.
-- * Home metros: every county of a conference's metro area belongs to it
--   (live: its main city's metro; proposal: the metro of each of its
--   anchors) — the whole metro, however far its county centres sit (the
--   Inland Empire, the NJ shore).  Beyond its home a conference still
--   reaches 160 km from its city centre (mig 1261, × traffic factor).
-- * New proposals for metro areas over the borderline bar left as open
--   ground (below).
-- Rerun scripts/pyramid-sea-borders.py after this.

CREATE TABLE IF NOT EXISTS pyramid_metro_areas (
    cbsa_code text PRIMARY KEY,
    title     text NOT NULL,
    kind      text NOT NULL CHECK (kind IN ('metro', 'micro')),
    csa_code  text,
    csa_title text
);
CREATE TABLE IF NOT EXISTS pyramid_metro_counties (
    fips      text PRIMARY KEY REFERENCES pyramid_counties(fips),
    cbsa_code text NOT NULL REFERENCES pyramid_metro_areas(cbsa_code),
    central   boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS pyramid_metro_counties_cbsa ON pyramid_metro_counties (cbsa_code);
COMMENT ON TABLE pyramid_metro_areas IS
    'mig 1265: OMB July 2023 core based statistical areas (Census list1_2023) — metro/micro areas and their combined area.';
COMMENT ON TABLE pyramid_metro_counties IS
    'mig 1265: county → its 2023 CBSA (Connecticut planning regions mapped back to the 8 old counties).';

