-- Each metro area's people.
CREATE OR REPLACE VIEW pyramid_metro_population AS
SELECT a.cbsa_code, a.title, a.kind, sum(k.population)::bigint AS population
  FROM pyramid_metro_areas a
  JOIN pyramid_metro_counties mc USING (cbsa_code)
  JOIN pyramid_counties k ON k.fips = mc.fips
 GROUP BY a.cbsa_code, a.title, a.kind;

-- The bar: the smallest metro area that anchors a live conference.
CREATE OR REPLACE VIEW pyramid_proposal_bar AS
SELECT mp.population AS bar, mp.title, m.competition_id AS conference_id
  FROM pyramid_main_cities m
  JOIN pyramid_competitions c ON c.id = m.competition_id AND c.kind = 'conference' AND c.is_active
  JOIN pyramid_metro_counties mc ON mc.fips = m.core_fips[1]
  JOIN pyramid_metro_population mp ON mp.cbsa_code = mc.cbsa_code
 ORDER BY mp.population
 LIMIT 1;
COMMENT ON VIEW pyramid_proposal_bar IS
    'mig 1265: the #apsl-pyramid proposal bar — the smallest metro area (people) that anchors a live conference.';

-- Home metros: county → the region whose metro area it is in.  Live
-- conferences first (their main city's metro), then non-developing
-- proposals (each anchor's metro).
CREATE OR REPLACE VIEW pyramid_region_homes AS
SELECT DISTINCT ON (fips) fips, conference_id, proposed_id
  FROM (SELECT mc.fips, m.competition_id AS conference_id, NULL::int AS proposed_id, 0 AS pri
          FROM pyramid_main_cities m
          JOIN pyramid_competitions c ON c.id = m.competition_id AND c.kind = 'conference' AND c.is_active
          JOIN pyramid_metro_counties h ON h.fips = ANY (m.core_fips)
          JOIN pyramid_metro_areas a ON a.cbsa_code = h.cbsa_code AND a.kind = 'metro'
          JOIN pyramid_metro_counties mc ON mc.cbsa_code = h.cbsa_code
        UNION ALL
        SELECT mc.fips, NULL, an.proposed_id, 1
          FROM pyramid_proposed_anchors an
          JOIN pyramid_proposed_conferences p ON p.id = an.proposed_id AND NOT p.developing
          JOIN pyramid_metro_counties h ON h.fips = an.fips
          JOIN pyramid_metro_areas a ON a.cbsa_code = h.cbsa_code AND a.kind = 'metro'
          JOIN pyramid_metro_counties mc ON mc.cbsa_code = h.cbsa_code) s
 ORDER BY fips, pri, conference_id, proposed_id;
COMMENT ON VIEW pyramid_region_homes IS
    'mig 1265: county → the conference (live main city, or a non-developing proposal''s anchor) whose metro area it is in.';

