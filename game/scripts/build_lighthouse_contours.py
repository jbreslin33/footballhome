#!/usr/bin/env python3
"""Build frontend/js/game/lighthouse-contours.js — ground contours for
Lighthouse Field from USGS 3DEP lidar elevation.

James wanted to see where the water goes. 3DEP (the US Geological
Survey's lidar bare-earth elevation, 1 m native) is fetched as a float
GeoTIFF from the public 3DEPElevation ImageServer, sampled on a 1 m grid
in site metres (same origin/axes as lighthouse-site.js: x east, z
south), and contoured with marching squares every 10 cm. Output is line
segments [x1, z1, x2, z2] per level, plus a coarse elevation grid so the
game can say how high any spot is.

Data: U.S. Geological Survey, 3D Elevation Program (public domain).
Usage: build_lighthouse_contours.py   (needs network; Pillow only)
"""
import io
import json
import math
import urllib.parse
import urllib.request

from PIL import Image

LAT0, LON0 = 40.008229, -75.124772
KX = 111320 * math.cos(math.radians(LAT0))
KZ = 110540
R = 6378137.0
X0, X1, Z0, Z1 = -140, 180, -160, 70      # site box, metres
STEP = 0.10                                # contour interval, m
LO, HI = 32.2, 34.4                        # field + edges (lidar range there)
OUT = 'frontend/js/game/lighthouse-contours.js'
URL = 'https://elevation.nationalmap.gov/arcgis/rest/services/3DEPElevation/ImageServer/exportImage'
UA = {'User-Agent': 'FootballHome-game/1.0 (footballhome.org)'}


def loc2ll(x, z):
    return LAT0 - z / KZ, LON0 + x / KX


def ll2m(lat, lon):
    return math.radians(lon) * R, math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)) * R


def main():
    la1, lo0 = loc2ll(X0 - 5, Z0 - 5)
    la0, lo1 = loc2ll(X1 + 5, Z1 + 5)
    mx0, my0 = ll2m(la0, lo0)
    mx1, my1 = ll2m(la1, lo1)
    res = 0.5 / math.cos(math.radians(LAT0))
    W, H = int((mx1 - mx0) / res), int((my1 - my0) / res)
    q = urllib.parse.urlencode({'bbox': f'{mx0},{my0},{mx1},{my1}', 'bboxSR': 3857, 'imageSR': 3857,
                                'size': f'{W},{H}', 'format': 'tiff', 'pixelType': 'F32',
                                'interpolation': 'RSP_BilinearInterpolation', 'f': 'json'})
    meta = json.load(urllib.request.urlopen(urllib.request.Request(URL + '?' + q, headers=UA), timeout=120))
    tif = urllib.request.urlopen(urllib.request.Request(meta['href'], headers=UA), timeout=120).read()
    dem = Image.open(io.BytesIO(tif))
    dv = dem.load()
    e = meta['extent']
    w, h = meta['width'], meta['height']

    def elev(x, z):
        lat, lon = loc2ll(x, z)
        mx, my = ll2m(lat, lon)
        X = (mx - e['xmin']) / (e['xmax'] - e['xmin']) * w - 0.5
        Y = (e['ymax'] - my) / (e['ymax'] - e['ymin']) * h - 0.5
        i, j = int(X), int(Y)
        fx, fy = X - i, Y - j
        a, b, c, d = dv[i, j], dv[i + 1, j], dv[i, j + 1], dv[i + 1, j + 1]
        return a * (1 - fx) * (1 - fy) + b * fx * (1 - fy) + c * (1 - fx) * fy + d * fx * fy

    xs = list(range(X0, X1 + 1))
    zs = list(range(Z0, Z1 + 1))
    g = [[elev(x, z) for x in xs] for z in zs]

    levels = []
    lv = math.ceil(LO / STEP) * STEP
    while lv <= HI + 1e-9:
        levels.append(round(lv, 2))
        lv += STEP
    out = []
    for L in levels:
        segs = []
        for j in range(len(zs) - 1):
            for i in range(len(xs) - 1):
                c = [(xs[i], zs[j], g[j][i]), (xs[i + 1], zs[j], g[j][i + 1]),
                     (xs[i + 1], zs[j + 1], g[j + 1][i + 1]), (xs[i], zs[j + 1], g[j + 1][i])]
                pts = []
                for k in range(4):
                    (ax, az, ae), (bx, bz, be) = c[k], c[(k + 1) % 4]
                    if (ae < L) != (be < L):
                        t = (L - ae) / (be - ae)
                        pts.append((round(ax + (bx - ax) * t, 1), round(az + (bz - az) * t, 1)))
                if len(pts) == 2:
                    segs += [pts[0][0], pts[0][1], pts[1][0], pts[1][1]]
                elif len(pts) == 4:
                    segs += [pts[0][0], pts[0][1], pts[1][0], pts[1][1],
                             pts[2][0], pts[2][1], pts[3][0], pts[3][1]]
        if segs:
            out.append({'z': L, 's': segs})
    grid = {'x0': X0, 'z0': Z0, 'step': 5,
            'h': [[round(g[j][i], 2) for i in range(0, len(xs), 5)] for j in range(0, len(zs), 5)]}
    with open(OUT, 'w') as fh:
        fh.write('// GENERATED by game/scripts/build_lighthouse_contours.py — do not hand-edit.\n')
        fh.write('// Ground elevation (m, NAVD88) from USGS 3DEP lidar (public domain), 10 cm contours,\n')
        fh.write('// site metres from LIGHTHOUSE_SITE.origin. levels[].s = [x1,z1,x2,z2,...] segments.\n')
        fh.write('window.LIGHTHOUSE_CONTOURS = ')
        json.dump({'step': STEP, 'levels': out, 'grid': grid}, fh, separators=(',', ':'))
        fh.write(';\n')
    print(OUT, len(out), 'levels', sum(len(l['s']) // 4 for l in out), 'segments')


if __name__ == '__main__':
    main()
