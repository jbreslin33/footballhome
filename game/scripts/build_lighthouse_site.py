#!/usr/bin/env python3
"""Build frontend/js/game/lighthouse-site.js from OpenStreetMap.

The game's ground is Lighthouse Field (199 E Erie Ave, Philadelphia).
This pulls the real outlines around it from OpenStreetMap (Overpass API)
— the recreation ground, pitches, buildings, roads, railways, parking,
the cemetery — and writes them as metres from a FIXED origin (the
Lighthouse Field centroid as mapped on 2026-10-22), x east, z south.

Map data © OpenStreetMap contributors, ODbL 1.0 — the attribution is
written into the output file. What OSM lacks or has out of date (the
barn, the rodeo ring, tree lines, today's pitch layout, the kids' 7v7
field) lives in the hand-edited lighthouse-layout.js, not here.

Usage:
  build_lighthouse_site.py [cached_overpass.json]
Without an argument it queries Overpass (needs network).
"""

import json
import math
import sys
import urllib.parse
import urllib.request

ORIGIN_LAT = 40.008229   # Lighthouse Field centroid (OSM way 762100596)
ORIGIN_LON = -75.124772
BBOX = (40.0035, -75.1320, 40.0135, -75.1170)   # S, W, N, E (~1.3 x 1.1 km)
OUT = 'frontend/js/game/lighthouse-site.js'

QUERY = """[out:json][timeout:60];
(way({s},{w},{n},{e});relation({s},{w},{n},{e})[type=multipolygon];
 node({s},{w},{n},{e})[natural=tree];);
out geom tags;""".format(s=BBOX[0], w=BBOX[1], n=BBOX[2], e=BBOX[3])

# Per carriageway: divided roads (Erie Ave) are mapped as two ways.
ROAD_WIDTH = {'primary': 11, 'secondary': 10, 'secondary_link': 6, 'tertiary': 10,
              'residential': 8, 'unclassified': 7, 'service': 4.5}
PATH_WIDTH = {'footway': 2, 'path': 2, 'cycleway': 2}


def fetch():
    req = urllib.request.Request(
        'https://overpass-api.de/api/interpreter',
        data=urllib.parse.urlencode({'data': QUERY}).encode(),
        headers={'User-Agent': 'FootballHome-game/1.0 (footballhome.org)',
                 'Accept': 'application/json'})
    with urllib.request.urlopen(req, timeout=90) as r:
        return json.load(r)


def main():
    data = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else fetch()
    kx = 111320 * math.cos(math.radians(ORIGIN_LAT))
    kz = 110540

    def xy(p):
        return [round((p['lon'] - ORIGIN_LON) * kx, 1),
                round(-(p['lat'] - ORIGIN_LAT) * kz, 1)]

    feats = []
    for e in data['elements']:
        t = e.get('tags', {})
        if e['type'] == 'node':
            feats.append({'k': 'tree', 'pts': [xy(e)]})
            continue
        if e['type'] != 'way' or 'geometry' not in e:
            continue
        pts = [xy(p) for p in e['geometry']]
        name = t.get('name')
        f = None
        if t.get('name') == 'Lighthouse Field':
            f = {'k': 'recreation'}
        elif 'building' in t:
            lv = t.get('building:levels')
            h = float(lv) * 3.3 if lv else None
            f = {'k': 'building', 'b': t['building'], 'h': h}
        elif t.get('leisure') == 'pitch':
            f = {'k': 'pitch', 'sport': t.get('sport', '')}
        elif t.get('leisure') == 'playground':
            f = {'k': 'playground'}
        elif t.get('landuse') == 'cemetery':
            f = {'k': 'cemetery'}
        elif t.get('landuse') in ('industrial', 'commercial', 'retail'):
            f = {'k': 'industrial'}
        elif t.get('amenity') == 'parking':
            f = {'k': 'parking'}
        elif t.get('amenity') in ('hospital', 'school', 'prison'):
            f = {'k': 'campus'}
        elif t.get('highway') in ROAD_WIDTH:
            f = {'k': 'road', 'w': ROAD_WIDTH[t['highway']]}
        elif t.get('highway') in PATH_WIDTH:
            f = {'k': 'path', 'w': PATH_WIDTH[t['highway']]}
        elif t.get('railway') in ('rail', 'abandoned', 'disused'):
            f = {'k': 'rail', 'live': t['railway'] == 'rail'}
        elif t.get('barrier') in ('fence', 'wall'):
            f = {'k': 'fence'}
        if f is None:
            continue
        if name:
            f['name'] = name
        f['id'] = e['id']
        f['pts'] = pts
        feats.append(f)

    # Draw order: big areas first, buildings last.
    order = ['cemetery', 'campus', 'industrial', 'recreation', 'parking',
             'pitch', 'playground', 'rail', 'road', 'path', 'fence', 'building', 'tree']
    feats.sort(key=lambda f: order.index(f['k']))
    out = {
        'origin': {'lat': ORIGIN_LAT, 'lon': ORIGIN_LON},
        'axes': 'metres; x east, z south',
        'attribution': 'Map data © OpenStreetMap contributors, ODbL 1.0',
        'generated_by': 'game/scripts/build_lighthouse_site.py',
        'features': feats,
    }
    with open(OUT, 'w') as fh:
        fh.write('// GENERATED by game/scripts/build_lighthouse_site.py — do not hand-edit.\n')
        fh.write('// Map data © OpenStreetMap contributors, ODbL 1.0 (openstreetmap.org/copyright).\n')
        fh.write('// Hand corrections (today\'s layout) live in lighthouse-layout.js.\n')
        fh.write('window.LIGHTHOUSE_SITE = ')
        json.dump(out, fh, separators=(',', ':'))
        fh.write(';\n')
    kinds = {}
    for f in feats:
        kinds[f['k']] = kinds.get(f['k'], 0) + 1
    print(OUT, kinds)


if __name__ == '__main__':
    main()
